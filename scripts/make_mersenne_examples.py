"""Generate Lean certificates for product pentanomials at Mersenne-prime exponents."""

import argparse

from make_witnesses import power_blocks


EXAMPLES = ((1279, 23, 34), (2203, 62, 135))


def emit(n, u, v, bits):
    if not (1 < n and 0 < u < v and u+v < n and bits > 0):
        raise ValueError("expected 1 < n, 0 < u < v, u+v < n, and positive block size")
    modulus = (1 << n) | (1 << (u+v)) | (1 << u) | (1 << v) | 1
    mersenne = (1 << n) - 1
    residue, blocks = power_blocks(mersenne, modulus, bits)
    if residue != 1:
        raise ValueError(f"the full exponent check failed in degree {n}")
    print(f"\nprivate theorem prime_{n} : (mersenne {n}).Prime :=")
    print(f"  lucas_lehmer_sufficiency {n} (by decide) (by norm_num)")
    print(f"\nset_option exponentiation.threshold {n} in")
    print(f"theorem primitiveProduct_{n}_{u}_{v} : Primitive (productCandidate {n} {u} {v}) := by")
    print(f"  apply primitive_product_of_mersenne_blocks (bits := {bits}) (by decide) (by decide +kernel) prime_{n} [")
    print(",\n".join(f"    0x{value:x}" for value in blocks) + "]")
    print("  decide +kernel")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--example", action="append", nargs=3, type=int, metavar=("N", "U", "V"),
                        help="certify this degree and pair of interior exponents")
    parser.add_argument("--bits", type=int, default=64, help="exponent bits per certificate block")
    args = parser.parse_args()
    print("import GF2Sparse.MersenneCertificate")
    print("\n/-! Generated by scripts/make_mersenne_examples.py. -/")
    print("\nnamespace GF2Sparse\n\nset_option maxRecDepth 16384\nset_option maxHeartbeats 4000000")
    for example in args.example or EXAMPLES:
        emit(*example, args.bits)
    print("\nend GF2Sparse")
