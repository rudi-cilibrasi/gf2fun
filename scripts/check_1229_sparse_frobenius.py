"""Check rational Frobenius maps on all irreducible degree-1229 pentanomials.

Run with `uv run --no-project --with numpy --with python-flint==0.9.0 python
scripts/check_1229_sparse_frobenius.py`. The --profiles option needs only FLINT.
The support CSV can be regenerated by census_1229_pentanomials.cpp --list.
"""

import argparse
import csv
import gzip
import hashlib
import json
from collections import Counter
from functools import cache

from check_factor_base import DATA, polynomial
from period_coordinate import CANDIDATES, DEGREE, mask_of


SUPPORTS = DATA / 'degree-1229-irreducible-supports.csv.gz'
SUPPORT_DIGEST = '50bd8d06fe2ad29d2bd2a8e3b33151c1d84455fc50a9aabacc2548402abc7db7'
CONTROL = DATA / 'degree-1229-q1024-certificate.json'


def support_table():
    import numpy as np
    if hashlib.sha256(gzip.decompress(SUPPORTS.read_bytes())).hexdigest() != SUPPORT_DIGEST:
        raise ValueError('support table digest mismatch')
    with gzip.open(SUPPORTS, 'rt', newline='') as stream:
        rows = csv.DictReader(stream)
        if rows.fieldnames != ['a', 'b', 'c', 'missing_mask']:
            raise ValueError('invalid support header')
        data = np.array([tuple(int(row[k]) for k in rows.fieldnames) for row in rows], dtype=np.int32)
    taps = [tuple(map(int, t)) for t in data[:, :3]]
    if (len(taps) != 319583 or taps != sorted(set(taps)) or any(
            not (0 < a < b < c < DEGREE and (a, b, c) < (DEGREE-c, DEGREE-b, DEGREE-a))
            for a, b, c in taps)):
        raise ValueError('invalid reciprocal representatives')
    counts = Counter(a for a, _, _ in taps)
    with (DATA / 'degree-1229-pentanomial-census.csv').open() as stream:
        expected = {int(row['smallest_tap']): int(row['irreducibles']) for row in csv.DictReader(stream)}
    if any(counts[a] != expected[a] for a in range(1, DEGREE//2 + 1)):
        raise ValueError('support counts disagree with the irreducibility census')
    with (DATA / 'degree-1229-order-exceptions.csv').open() as stream:
        exceptions = {tuple(int(row[k]) for k in ('a', 'b', 'c')): int(row['missing_mask'])
                      for row in csv.DictReader(stream)}
    if {t: int(flag) for t, flag in zip(taps, data[:, 3]) if flag} != exceptions:
        raise ValueError('support flags disagree with the order census')
    return data[:, :3].T.copy()


class SplitFibers:
    """Resultant evaluations at split fibers in an auxiliary binary field."""

    def __init__(self, taps, control, bits, modulus):
        import numpy as np
        self.taps = taps
        self.control_terms = [i for i in range(DEGREE + 1) if control >> i & 1]
        self.order = (1 << bits) - 1
        self.powers = np.empty(self.order, dtype=np.uint16)
        value = 1
        for i in range(self.order):
            self.powers[i] = value
            value <<= 1
            if value > self.order:
                value ^= modulus
        if value != 1 or len(np.unique(self.powers)) != self.order:
            raise ArithmeticError('invalid field generator')
        self.logs = np.full(self.order + 1, -1, dtype=np.int32)
        self.logs[self.powers] = np.arange(self.order)
        elements = np.arange(self.order + 1, dtype=np.int32)
        self.values = [elements*0, elements*0 + 1]
        for mask in range(2, 64):
            prev = self.values[mask//2]
            product = self.powers[(self.logs[elements] + self.logs[prev]) % self.order]
            self.values.append(np.where((elements == 0) | (prev == 0), 0, product) ^ (mask % 2))
        self.orbit = {}
        for point in range(1, self.order + 1):
            if point not in self.orbit:
                cur = point
                for j in range(bits):
                    self.orbit[cur] = (point, 1 << j)
                    cur = int(self.powers[2*self.logs[cur] % self.order])
                    if cur == point:
                        break

    def evaluations(self, point, indices=None):
        import numpy as np
        powers = self.powers[self.logs[point]*np.arange(DEGREE + 1) % self.order]
        a, b, c = self.taps
        if indices is None:
            values = np.append(powers[0] ^ powers[DEGREE] ^ powers[a] ^ powers[b] ^ powers[c],
                               np.bitwise_xor.reduce(powers[self.control_terms]))
        else:
            # The dense control has the last index, immediately after the sparse table.
            sparse = indices[indices < len(a)]
            values = powers[0] ^ powers[DEGREE] ^ powers[a[sparse]] ^ powers[b[sparse]] ^ powers[c[sparse]]
            if len(sparse) < len(indices):
                values = np.append(values, np.bitwise_xor.reduce(powers[self.control_terms]))
        if np.any(values == 0):
            raise ArithmeticError('a polynomial has a root in the auxiliary field')
        return self.logs[values]

    @cache
    def full_column(self, point):
        return self.evaluations(point).astype('uint16')

    def survivors(self, u, v, indices=None):
        import numpy as np
        primary = indices is None
        degree = max(u, v).bit_length() - 1
        num, den = self.values[u], self.values[v]
        quotients = self.powers[(self.logs[num] - self.logs[den]) % self.order].astype(np.int32)
        image = np.where(den == 0, -1, np.where(num == 0, 0, quotients))
        sizes = np.bincount(image[image >= 0], minlength=self.order + 1)
        for point in np.flatnonzero(sizes == degree):
            if point < 2 or self.orbit[point][0] != point:
                continue
            # Norm_f(v) is one. Split Res(f,u+point*v) in this fiber.
            leading = (u >> degree) ^ ((v >> degree) * int(point))
            coeffs = Counter({point: -1})
            for root in np.flatnonzero(image == point):
                rep, weight = self.orbit[root]
                coeffs[rep] += weight
            total = DEGREE * int(self.logs[leading])
            for rep, weight in coeffs.items():
                if primary:
                    column = self.full_column(rep)
                    if indices is not None:
                        column = column[indices]
                    total = total + weight * column.astype(np.int32)
                else:
                    total = total + weight * self.evaluations(rep, indices).astype(np.int64)
            keep = total % self.order == 0
            indices = np.flatnonzero(keep) if indices is None else indices[keep]
            if not len(indices):
                break
        if indices is None:
            raise ArithmeticError(f'no split fiber for {u}/{v}')
        return indices


def check_census():
    taps = support_table()
    candidates = len(taps[0])
    control = int(json.loads(CONTROL.read_text())['modulus_hex'], 16)
    first = SplitFibers(taps, control, 12, 0x1053)
    second = SplitFibers(taps, control, 16, 0x1100B)
    maps = Counter()
    hits = []
    residues = 0
    x = polynomial(2)
    for u in range(1, 64):
        for v in range(1, 64):
            # A reduced binary fraction is a square exactly when both masks use only even powers.
            if not (u | v) & 0b101010 or polynomial(u).gcd(polynomial(v)) != 1:
                continue
            degree = max(u, v).bit_length() - 1
            maps[degree] += 1
            if (u, v) == (2, 1):
                continue
            indices = first.survivors(u, v)
            if len(indices):
                indices = second.survivors(u, v, indices)
            for index in indices:
                residues += 1
                mask = control if index == candidates else (1 << DEGREE) + 1 + sum(
                    1 << int(i) for i in taps[:, index])
                f = polynomial(mask)
                common, inverse, _ = polynomial(v).xgcd(f)
                if common != 1:
                    raise ArithmeticError('denominator has a common factor with the modulus')
                w = polynomial(u) * inverse % f
                if f.compose_mod(w, f) == 0:
                    t = x
                    for j in range(DEGREE):
                        if t == w:
                            hits.append((int(index), u, v, j))
                            break
                        t = t*t % f
                    else:
                        raise ArithmeticError('image root is outside the Frobenius orbit')
    if maps != {1: 6, 2: 18, 3: 96, 4: 360, 5: 1536} or residues != 1 or hits != [(candidates, 37, 10, 1219)]:
        raise ArithmeticError(f'unexpected maps {maps} or exact hits {hits}')
    print(f'{candidates} reciprocal representatives, {sum(maps.values())} separable maps, '
          f'{residues} pair reached the original-field check.')
    print('The only nonidentity match was the dense control, with Frobenius exponent 1219.')


def check_profiles():
    """Find every rational representative of height at most 205 for each conjugate."""
    height = 205
    x = polynomial(2)
    for name, taps in CANDIDATES.items():
        tail = 1 + sum(1 << i for i in taps)
        f = polynomial((1 << DEGREE) + tail)
        hits = {}
        t = x
        for j in range(DEGREE):
            a, b, c, d = f, t, polynomial(0), polynomial(1)
            while b.degree() > height:
                quotient, rem = divmod(a, b)
                a, b, c, d = b, rem, d, c + quotient*d
            if d.degree() <= height:
                if b.gcd(d) != 1 or b != t*d % f:
                    raise ArithmeticError('invalid rational reconstruction')
                hits[j] = (mask_of(b), mask_of(d))
            t = t*t % f
        expected = {j: (1 << (1 << j), 1) for j in range(8)}
        expected[10] = (tail, 1 << height)
        if t != x or hits != expected:
            raise ArithmeticError(f'unexpected Frobenius representatives for {name}')
        print(f'{name}: all {DEGREE} conjugates checked, least nonidentity separable height {height}.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profiles', action='store_true', help='only check the two individual height profiles')
    args = parser.parse_args()
    if not args.profiles:
        check_census()
    check_profiles()
