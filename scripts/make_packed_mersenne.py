"""Emit independently replayable Lean blocks for a sparse polynomial of Mersenne-prime degree."""

import argparse


def make_stages(n):
    k = (n - 1).bit_length()
    full = (1 << (2 << k)) - 1
    return [(s, full // ((1 << s) + 1)) for s in (1 << j for j in reversed(range(k)))]


def advance(value, n, taps, stages, steps):
    for _ in range(steps):
        for shift, mask in stages:
            value = (value ^ (value << shift)) & mask
        value <<= 1
        while high := value >> n:
            for tap in taps:
                value ^= high << tap
    return value


def chain(names, lemma):
    if len(names) == 1:
        return names[0]
    mid = len(names) // 2
    return f"{lemma} ({chain(names[:mid], lemma)}) ({chain(names[mid:], lemma)})"


def emit(n, interior, block, product):
    taps = [n, *sorted(interior, reverse=True), 0]
    stages = make_stages(n)
    fuel = (n - 1) // (n - max(interior)) + 2
    support = ", ".join(map(str, taps))
    print("import GF2Sparse.PackedSquare")
    if len(interior) == 1:
        print("import GF2Sparse.Progressions")
    print(f"\n/-! Degree-{n} certificate generated by scripts/make_packed_mersenne.py. -/")
    print("\nnamespace GF2Sparse\n\nopen PackedSquare")
    print(f"\nset_option maxRecDepth {max(32000, 2*n)}\nset_option maxHeartbeats 16000000")
    print(f"set_option exponentiation.threshold {2 << (n-1).bit_length()}")
    print(f"\nprivate def stages := stagesFor {(n-1).bit_length()}")
    print(f"private def taps : List ℕ := [{support}]")

    basis, powers = [], []
    value = 1
    for start in range(0, n, block):
        steps = min(block, n - start)
        bname, pname = f"basis{start}", f"power{start}"
        end = advance(value, n, taps, stages, steps)
        def label(offset):
            return f"residue{offset}" if 0 < offset < n else "1"
        if start + steps < n:
            print(f"\nprivate def {label(start+steps)} : ℕ := 0x{end:x}")
        print(f"\nprivate theorem {bname} : BasisOn stages {start} {steps} :=")
        print("  basisOn_of_check (by decide +kernel)")
        print(f"\nprivate theorem {pname} : PowerBlock {n} {n} {fuel} stages taps {steps} "
              f"{label(start)} {label(start+steps)} := ⟨by decide +kernel⟩")
        value = end
        basis.append(bname)
        powers.append(pname)
    if value != 1:
        raise ValueError(f"the full exponent failed in degree {n}")

    modulus = (1 << n) - 1
    ll_value = 4 % modulus
    lucas = []
    for start in range(0, n-2, block):
        steps = min(block, n-2-start)
        end = start + steps
        for _ in range(steps):
            square = ll_value * ll_value
            ll_value = (square & modulus) + (square >> n) - 2
            if ll_value >= modulus:
                ll_value -= modulus
            elif ll_value < 0:
                ll_value += modulus
        if end < n-2:
            print(f"\nprivate def lucasResidue{end} : ℕ := 0x{ll_value:x}")
        begin_label = f"lucasResidue{start}" if start else f"(4 % mersenne {n})"
        end_label = f"lucasResidue{end}" if end < n-2 else "0"
        name = f"lucas{start}"
        print(f"\nprivate theorem {name} : LucasBlock (mersenne {n}) {steps} {begin_label} {end_label} :=")
        print("  ⟨by decide +kernel⟩")
        lucas.append(name)
    if not lucas or ll_value:
        raise ValueError(f"the Lucas–Lehmer test failed for exponent {n}")

    if product:
        u, v = sorted(interior)[:2]
        print(f"\ntheorem primitiveProduct_{n}_{u}_{v} : Primitive (productCandidate {n} {u} {v}) := by")
        print("  rw [← decode_productMask]")
    elif len(interior) == 3:
        c, b, a = sorted(interior, reverse=True)
        print("\nopen Polynomial")
        print(f"\ntheorem primitivePentanomial_{n}_{c}_{b}_{a} :")
        print(f"    Primitive (X^{n}+X^{c}+X^{b}+X^{a}+1 : BinaryPoly) := by")
        print("  rw [← decode_fiveTermMask]")
    else:
        a = interior[0]
        print(f"\ntheorem primitiveTrinomial_{n}_{a} : Primitive (trinomial {n} {a}) := by")
        print(f"  have hdecode : decode (xorShifts taps 1) = trinomial {n} {a} := by")
        print(f"    exact decode_trinomial_taps {n} {a}")
        print("  rw [← hdecode]")
    print(f"  apply primitive_of_run (by decide : 1 < {n}) (by decide +kernel)")
    print(f"    (mersenne_prime_of_lucas_blocks (by decide) ({chain(lucas, 'LucasBlock.append')}))")
    print(f"    (checkBasis_of_basisOn ({chain(basis, 'BasisOn.append')}))")
    print(f"    (by decide +kernel) ({chain(powers, 'PowerBlock.append')}).checked")
    print("\nend GF2Sparse")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--product", nargs=3, type=int, metavar=("N", "U", "V"))
    group.add_argument("--trinomial", nargs=2, type=int, metavar=("N", "A"))
    group.add_argument("--pentanomial", nargs=4, type=int, metavar=("N", "A", "B", "C"))
    parser.add_argument("--block", type=int, default=256)
    args = parser.parse_args()
    if args.product:
        n, u, v = args.product
        interior = [u, v, u+v]
    elif args.pentanomial:
        n, *interior = args.pentanomial
    else:
        n, a = args.trinomial
        interior = [a]
    if n <= 2 or args.block < 1 or len(interior) != len(set(interior)) or not all(0 < a < n for a in interior):
        parser.error("expected a degree above two, a positive block size and distinct interior exponents strictly between zero and n")
    emit(n, interior, args.block, bool(args.product))
