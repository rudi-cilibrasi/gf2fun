"""Emit packed Lean order checks for a consecutive interval of product pentanomial witnesses."""

import argparse
import csv
import json
from pathlib import Path

from make_witnesses import prime_certificates, prime_refs, table_factors


def rows_for(start, stop, paths):
    rows = {}
    for path in paths:
        with path.open() as source:
            for row in csv.DictReader(source):
                n, u, v = (int(row[key]) for key in ("degree", "u", "v"))
                if start <= n <= stop:
                    if n in rows or not 0 < u < v < n or u + v >= n:
                        raise ValueError(f"invalid or repeated witness in degree {n}")
                    rows[n] = (u, v)
    missing = set(range(start, stop + 1)) - rows.keys()
    if missing:
        raise ValueError(f"missing witness in degree {min(missing)}")
    return rows


def emit_separate_powers(n, u, v, factors):
    """Let the kernel release each prime-index computation before checking the next."""
    primes = sorted(set(factors))
    print(f"\nprivate def groupFactors{n} : List ProvenPrime := {prime_refs(factors)}")
    print(f"\nprivate abbrev primePower{n} (p : ℕ) := PackedSquare.nontrivialPower")
    print(f"  {n} {n//(n-u-v)+2} (PackedSquare.stagesFor {(n-1).bit_length()}) "
          f"[{n}, {u+v}, {u}, {v}, 0] ((2^{n}-1)/p)")
    for p in primes:
        print(f"\nprivate theorem power{n}_{p} : primePower{n} {p} = true := by decide +kernel")
    print(f"\nprivate theorem checks{n} : PackedSquare.checkOrder {n} {u} {v}")
    print(f"    (groupFactors{n}.map Subtype.val) = true := by")
    print("  unfold PackedSquare.checkOrder")
    print("  refine Bool.and_eq_true_iff.mpr ⟨?_, ?_⟩")
    print("  · decide +kernel")
    print(f"  · change ([{', '.join(map(str, primes))}] : List ℕ).all primePower{n} = true")
    print("    simp only [List.all_cons, List.all_nil, Bool.true_and,")
    for i in range(0, len(primes), 4):
        print("      " + ", ".join(f"power{n}_{p}" for p in primes[i:i+4])
              + ("," if i+4 < len(primes) else "]"))
    print(f"\ntheorem primitiveProduct_{n}_{u}_{v} : Primitive (productCandidate {n} {u} {v}) := by")
    print(f"  apply PackedSquare.primitive_product_of_checkOrder (by decide) _ _ (checks{n})")
    print("  intro p hp")
    print("  obtain ⟨v, _, rfl⟩ := List.mem_map.1 hp")
    print("  exact v.property")
    print(f"\nprivate def row{n} := PackedSquare.productEntry {n} {u} {v} groupFactors{n} checks{n}")


def emit(start, stop, rows, table, lucas_factors, separate_powers=False):
    factors = {n: table_factors(n, table) for n in range(start, stop + 1)}
    proofs = prime_certificates(sorted({p for ps in factors.values() for p in ps}), lucas_factors)
    print("import GF2Sparse.PackedOrder")
    print("\n/-! Generated by scripts/make_packed_table.py from the public witness CSV. -/")
    print("\nnamespace GF2Sparse\n\nset_option maxRecDepth 16384\nset_option maxHeartbeats 4000000")
    if separate_powers:
        print("set_option Elab.async false")
    for p, proof in proofs.items():
        print(f"\nprivate def p{p} : ProvenPrime := {proof}")
    for n, ps in factors.items():
        u, v = rows[n]
        if separate_powers:
            emit_separate_powers(n, u, v, ps)
        else:
            print(f"\nprivate def row{n} := PackedSquare.productEntry {n} {u} {v} {prime_refs(ps)} (by decide +kernel)")
    print("\nprivate def rows : List {k : ℕ // HasPrimitiveProduct k} := [")
    for n in range(start, stop + 1, 8):
        end = min(stop + 1, n + 8)
        print("  " + ", ".join(f"row{i}" for i in range(n, end)) + ("," if end <= stop else "]"))
    print(f"\ntheorem primitiveProduct_{start}_to_{stop} (n : ℕ) (hlo : {start} ≤ n) (hhi : n ≤ {stop}) :")
    print(f"    HasPrimitiveProduct n := covers_range rows {start} {stop-start+1} (by decide +kernel) n hlo (by omega)")
    print("\nend GF2Sparse")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("start", type=int)
    parser.add_argument("stop", type=int)
    parser.add_argument("--factor-table", action="append", type=Path, required=True)
    parser.add_argument("--csv", action="append", type=Path)
    parser.add_argument("--separate-powers", action="store_true",
                        help="emit a separate kernel-checked theorem for each prime-index power")
    args = parser.parse_args()
    if not 5 <= args.start <= args.stop:
        parser.error("expected 5 <= start <= stop")
    data = Path(__file__).resolve().parents[1] / "data"
    paths = args.csv or sorted(data.glob("product-witnesses-*.csv"))
    table = {}
    for path in args.factor_table:
        with path.open() as source:
            part = json.load(source)
            table.update(part.get("table2-_data", part))
    # FactorDB supplies these slow p-1 factorizations. prime_certificates checks each one.
    with (data / "packed-lucas-factors.json").open() as source:
        lucas_factors = {int(p): factors for p, factors in json.load(source).items()}
    emit(args.start, args.stop, rows_for(args.start, args.stop, paths), table, lucas_factors, args.separate_powers)
