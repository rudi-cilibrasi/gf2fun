"""Verify the projective-line order certificate for a degree-4112 binary polynomial."""

import argparse
import csv
import gzip
import json
import math
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from flint import fmpz, nmod_poly

from check_product_range import prime_index_powers


Q = 256
K = Q**2
N = 16 * (Q + 1)
ORDER = 2**N - 1
A = (K - 1) * (Q + 1)
B = ORDER // A
BASE_TAPS = (0, 1, 4, 6, 16)
TAPS = (0, 1, 4, 6, 16, 257, 518, 1028, 1030, 1542, 4112)
TABLE = Path(__file__).resolve().parents[1] / "data/degree-4112-projective-logs.csv.gz"


def field_and_root():
    x = nmod_poly([0, 1], 2)
    modulus = sum(x**i for i in TAPS)
    return modulus, x, x**(Q+1) + x


def check_irreducible(f, x):
    # Rabin's criterion. The distinct primes dividing 4112 are 2 and 257.
    if f.degree() != N or x.pow_mod(2**N, f) != x:
        raise ValueError("full Frobenius test failed")
    for p in (2, 257):
        if (x.pow_mod(2**(N//p), f) - x).gcd(f) != 1:
            raise ValueError(f"proper subfield at degree {N//p}")


def check_fields():
    f, x, a = field_and_root()
    if sum(a**i for i in BASE_TAPS) != f:
        raise ValueError("binary polynomial does not match the relative equation")
    check_irreducible(f, x)
    if A != 3*5*17*257**2 or A*B != ORDER or math.gcd(A, B) != 1:
        raise ValueError("incorrect group order decomposition")
    for p in (3, 5, 17, 257):
        if x.pow_mod(ORDER//p, f) == 1:
            raise ValueError(f"missing prime power at {p}")


class ConstantField:
    """Power-basis encodings for the constant field generated by a = x^257 + x."""

    def __init__(self):
        base = sum(1 << i for i in BASE_TAPS)
        self.exp = []
        self.log = [-1] * K
        value = 1
        for j in range(K-1):
            if self.log[value] != -1:
                raise ValueError("the residue of the base variable has short order")
            self.exp.append(value)
            self.log[value] = j
            value <<= 1
            if value & K:
                value ^= base
        if value != 1:
            raise ValueError("invalid constant field")

    def multiply(self, x, y):
        if x == 0 or y == 0:
            return 0
        return self.exp[(self.log[x] + self.log[y]) % (K-1)]

    def divide(self, x, y):
        if y == 0:
            raise ZeroDivisionError("constant field division by zero")
        return self.exp[(self.log[x] - self.log[y]) % (K-1)] if x else 0

    def power(self, x, e):
        return self.exp[self.log[x]*e % (K-1)] if x else int(e == 0)

    def successor(self, c):
        if c == K:  # Infinity represents the constant 1.
            return 0
        denominator = 1 ^ self.power(c, Q)
        return self.divide(2, denominator) if denominator else K


def direction_orbits(field):
    seen = set()
    orbits = []
    for c in [K, *range(K)]:
        if c in seen:
            continue
        current = c
        orbit = []
        while current not in seen:
            seen.add(current)
            orbit.append(current)
            current = field.successor(current)
        if current != c:
            raise ValueError("the projective map is not a permutation")
        orbits.append(orbit)
    return orbits


def check_powers(rows):
    f, x, a = field_and_root()
    basis = [a**j for j in range(16)]
    for c, exponent in rows:
        if not 0 <= exponent < B:
            raise ValueError(f"exponent outside the quotient at {c}")
        linear = x**0
        if c < K:
            linear = x + sum(basis[j] for j in range(16) if (c >> j) & 1)
        if x.pow_mod(A*exponent, f) != linear.pow_mod(A, f):
            raise ValueError(f"projected power failed at direction {c}")


def check_target(exponent):
    path = TABLE.with_name("degree-4112-pentanomial-target.json")
    record = json.loads(path.read_text())
    f, x, _ = field_and_root()
    if record["sparse_support"] != [0, 1, 12, 23, N]:
        raise ValueError("unexpected target pentanomial")
    target = sum(x**j for j in record["sparse_support"])
    check_irreducible(target, x)
    factors = record["known_prime_factors"]
    known = math.prod(factors)
    cofactor, remainder = divmod(ORDER, known)
    if remainder or cofactor <= 1 or math.gcd(known, cofactor) != 1:
        raise ValueError("invalid partial factorization")
    primes = sorted(set(factors))
    if any(not fmpz(p).is_prime() for p in primes):
        raise ValueError("incorrect claimed prime")
    for p, value in prime_index_powers(x, ORDER, primes, target):
        if value == 1:
            raise ValueError(f"target has a missing order factor at {p}")
    if x.pow_mod(known, target) == 1:
        raise ValueError("trivial projection of the target")
    # The order of 2 modulo the cofactor is N, so x^known in the primitive
    # model has minimal polynomial of degree N. One zero evaluation identifies it.
    if pow(2, N, cofactor) != 1 or any(pow(2, N//p, cofactor) == 1 for p in (2, 257)):
        raise ValueError("the projected generator lies in a proper subfield")
    bits = int(record["projected_minpoly_hex"], 16)
    if bits.bit_length() != N+1:
        raise ValueError("incorrect degree of the projected polynomial")
    h = nmod_poly([(bits >> j) & 1 for j in range(N+1)], 2)
    if h.compose_mod(x.pow_mod(known, f), f) != 0:
        raise ValueError("the projected generator does not satisfy the certificate")
    print(f"Verified {len(primes)} known prime-index tests for the pentanomial, "
          f"a {known.bit_length()}-bit order divisor, and its nontrivial projection "
          f"onto the {len(str(cofactor))}-digit cofactor component.")
    if exponent is not None:
        if not 0 <= exponent < cofactor:
            raise ValueError("the submitted exponent must be between zero and the cofactor minus one")
        if h.compose_mod(x.pow_mod(known*exponent, target), target) != 0:
            raise ValueError("the submitted exponent does not certify the pentanomial")
        print("Verified the remaining cofactor and the full order of the pentanomial.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jobs", type=int, default=1)
    parser.add_argument("--target", action="store_true", help="verify the five-term candidate and its scalar reduction")
    parser.add_argument("--target-exponent", type=int, help="test a proposed scalar for the five-term candidate")
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    check_fields()
    orbits = direction_orbits(ConstantField())
    with gzip.open(TABLE, "rt", newline="") as src:
        reader = csv.DictReader(src)
        if reader.fieldnames != ["representative", "exponent"]:
            raise ValueError("invalid table header")
        rows = [(int(row["representative"]), int(row["exponent"])) for row in reader]
    if [c for c, _ in rows] != [orbit[0] for orbit in orbits]:
        raise ValueError("the table must contain each orbit representative exactly once")
    jobs = min(args.jobs, len(rows))
    if jobs == 1:
        check_powers(rows)
    else:
        with ProcessPoolExecutor(jobs) as pool:
            for _ in pool.map(check_powers, [rows[i::jobs] for i in range(jobs)]):
                pass
    print(f"Verified {len(rows)} orbit powers covering {sum(map(len, orbits))} projective "
          f"directions, irreducibility, and the four small-prime order checks in degree {N}.")
    if args.target or args.target_exponent is not None:
        check_target(args.target_exponent)


if __name__ == "__main__":
    main()
