"""Check quotient and product multiplicities for sparse binary polynomials."""

import argparse
from collections import Counter
from functools import cache
from itertools import combinations, combinations_with_replacement
from math import gcd

from check_factor_base import irreducible, modulus, polynomial
from check_ore_lifts import order_index
from make_witnesses import mersenne_factors


def multiplicity_bounds(support):
    """Try every partition into the terms of B(X^d) and X^m A(X^d)."""
    quotient = product = support[-1]
    for size in range(1, len(support)):
        for upper in combinations(support[1:], size):
            lower = [e for e in support if e not in upper]
            m = upper[0]
            d = gcd(*lower, *(e-m for e in upper))
            if d == 0:
                continue
            a, b = (upper[-1]-m)//d, lower[-1]//d
            quotient = min(quotient, a+b)
            product = min(product, max(a, b))
    return quotient, product


@cache
def multiplicities(n, h):
    """Use the exponents of the conjugates in the cyclic group generated by a root."""
    roots = [pow(2, i, h) for i in range(n)]
    if len(set(roots)) != n:
        raise ArithmeticError(f"order {h} does not have degree {n}")
    quotients = Counter((x-y) % h for x in roots for y in roots if x != y)
    products = Counter((x+y) % h for x, y in combinations_with_replacement(roots, 2))
    return max(quotients.values()), max(products.values()), max(v for z, v in products.items() if z)


def check_irreducibles(limit):
    checked = degree15 = forced151 = 0
    for n in range(4, limit+1):
        factors = mersenne_factors(n)
        for taps in combinations(range(1, n), 3):
            if gcd(n, *taps) != 1 or not irreducible(modulus(n, taps)):
                continue
            support = (0, *taps, n)
            q, p = multiplicity_bounds(support)
            h = ((1 << n)-1)//order_index(support, factors)
            qr, pr, pr_nonidentity = multiplicities(n, h)
            reciprocal = taps == tuple(n-e for e in reversed(taps))
            if qr > q or (pr_nonidentity if reciprocal else pr) > p:
                raise ArithmeticError(f"multiplicity bound failed for {support}, order {h}")
            checked += 1
            if n == 15:
                degree15 += 1
                if q < 5:
                    if h % 151:
                        raise ArithmeticError(f"the order for {support} omits 151")
                    forced151 += 1
    print(f"Checked both multiplicities for {checked} irreducible pentanomials through degree {limit}.")
    if limit >= 15:
        print(f"In degree 15, the split-support test forces 151 into {forced151} of {degree15} root orders.")


def check_family(limit):
    x = polynomial(2)
    phi5 = polynomial(31)
    for n in range(4, limit+1):
        f = modulus(n, (1, 2, n-1))
        if f.gcd(f.derivative()) != 1 or f.gcd(f.reverse()) != (phi5 if n % 5 == 4 else 1):
            raise ArithmeticError(f"incorrect separability or inverse-pair criterion at degree {n}")
        period = 1
        for factor, multiplicity in f.factor()[1]:
            support = tuple(i for i in range(factor.degree()+1) if factor[i])
            d = factor.degree()
            h = ((1 << d)-1)//order_index(support, mersenne_factors(d))
            if multiplicity != 1:
                raise ArithmeticError(f"repeated factor at degree {n}")
            period = period//gcd(period, h)*h
        if x.pow_mod(period, f) != 1 or 3*(period-1) < n*(n-1):
            raise ArithmeticError(f"period lower bound failed at degree {n}")
    print(f"Checked the full quotient period and reciprocal gcd of the explicit family through degree {limit}.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--through", type=int, default=24, help="maximum degree for the irreducible census")
    parser.add_argument("--family-through", type=int, default=64, help="maximum degree for the full quotient checks")
    args = parser.parse_args()
    if min(args.through, args.family_through) < 4:
        parser.error("expected degrees of at least four")
    check_irreducibles(args.through)
    check_family(args.family_through)
