def seventh_root(modulus):
    """Find a seventh root of X by splitting off the 7-primary component."""
    x = nmod_poly([0, 1], 2)
    group_size = (1 << modulus.degree()) - 1
    if x.pow_mod(group_size // 7, modulus) != 1:
        return None
    coprime_part = group_size
    while coprime_part % 7 == 0:
        coprime_part //= 7
    seven_part = group_size // coprime_part
    root = x.pow_mod(pow(7, -1, coprime_part), modulus)
    if root.pow_mod(7, modulus) == x:
        return root
    for mask in count(2):
        candidate = from_support(support(mask)).pow_mod(coprime_part, modulus)
        if candidate.pow_mod(seven_part // 7, modulus) != 1:
            break
    for _ in range(seven_part // 7):
        root = root * candidate % modulus
        if root.pow_mod(7, modulus) == x:
            return root
    raise ArithmeticError("failed to extract a seventh root")


def certificates():
    for interior_count in (1, 3):
        for exponents in combinations(range(1, 12), interior_count):
            seed = (0, *exponents, 12)
            if not primitive(12, sum(1 << i for i in seed), (3, 5, 7, 13)):
                continue
            modulus = from_support(lifted_support(seed))
            witness = seventh_root(modulus)
            if witness is not None:
                mask = sum(int(bit) << i for i, bit in enumerate(witness.coeffs()))
                yield exponents, mask


