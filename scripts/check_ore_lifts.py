"""Test full multiplicative order after Ore lifting every sparse primitive seed through degree ten."""

import argparse
import json
from itertools import combinations

from flint import nmod_poly

from make_witnesses import emit_block_powers, emit_certified_powers, prime_certificates, primitive, table_factors


def lifted_support(support):
    return tuple((1 << i) - 1 for i in support)


def order_index(support, factors):
    """Divide the known group size by primes as long as the power remains one."""
    degree = support[-1]
    coefficients = [0] * (degree + 1)
    for exponent in support:
        coefficients[exponent] = 1
    modulus = nmod_poly(coefficients, 2)
    x = nmod_poly([0, 1], 2)
    size = (1 << degree) - 1
    if x.pow_mod(size, modulus) != 1:
        raise ValueError(f"failed full exponent check on {support}")
    order = size
    for p in factors:
        if order % p == 0 and x.pow_mod(order // p, modulus) == 1:
            order //= p
    return size // order


def survey(table):
    for s in range(2, 11):
        factors = table_factors(s, table)
        lift_factors = table_factors((1 << s) - 1, table)
        count = 0
        exceptional = []
        for interior_count in (1, 3):
            for interior in combinations(range(1, s), interior_count):
                support = (0, *interior, s)
                if not primitive(s, sum(1 << i for i in support), factors):
                    continue
                count += 1
                index = order_index(lifted_support(support), lift_factors)
                if index > 1:
                    exceptional.append((support, index))
        print(f"seed degree {s}, primitive lifts {count - len(exceptional)}/{count}")
        for support, index in exceptional:
            print(f"  seed {support}, multiplicative index {index}")


def emit(table):
    examples = ((9, 4), (10, 3))
    degrees = [(1 << s) - 1 for s, _ in examples]
    factors = {n: table_factors(n, table) for n in degrees}
    proofs = prime_certificates(p for n in degrees for p in factors[n])
    print("import GF2Sparse.Table\nimport GF2Sparse.Progressions\n\n/-! Generated by scripts/check_ore_lifts.py --lean. -/")
    print("\nnamespace GF2Sparse\n\nopen Polynomial\n\nset_option maxRecDepth 16384")
    print("set_option maxHeartbeats 4000000\n")
    for p, proof in proofs.items():
        print(f"private def p{p} : ProvenPrime := {proof}")
    for s, a in examples:
        _, k, n = lifted_support((0, a, s))
        mask = (1 << n) | (1 << k) | 1
        print(f"\nnamespace Ore{s}")
        emit_block_powers(n, mask, factors[n], 64, f"2 ^ {n} ^^^ 2 ^ {k} ^^^ 1")
        print(f"\nset_option exponentiation.threshold {n} in")
        print(f"theorem primitive_trinomial : Primitive (trinomial {n} {k}) := by")
        print(f"  have he : decode modulus = trinomial {n} {k} := by")
        print("    simp only [modulus, decode_xor, decode_pow_two, decode_one, trinomial, add_assoc]")
        print("  rw [← he]")
        emit_certified_powers(n, factors[n])
        print(f"\nend Ore{s}")
    print("\nend GF2Sparse")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--factor-table", required=True, type=argparse.FileType("r"),
                        help="Cunningham table2-_data JSON or a map of degrees to prime factors")
    parser.add_argument("--lean", action="store_true", help="emit the two large primitive certificates")
    args = parser.parse_args()
    with args.factor_table as source:
        data = json.load(source)
    table = data.get("table2-_data", data)
    if args.lean:
        emit(table)
    else:
        survey(table)
